// Figma code syntax for the variables (Plan 216, Phase E).
//
// A Figma variable can carry the name a developer uses for it in code. Dev Mode shows it
// next to the variable, so a designer reads `var(--space-button-padding-x-md)` instead of
// `button/padding-x/md`. Token Bridge sets it on Pull from a committed file,
// packages/tokens/io/code-syntax/web.json, that this module derives from the sync tokens.
//
// The CSS name comes from the same function the Style Dictionary build uses
// (packages/tokens/lib/css-variable.js), so the code syntax cannot disagree with the CSS.
// The check below also proves every name is declared in the built CSS.
//
// Like the text style definitions, the file lives outside io/sync (Push writes io/sync;
// derived data is never pushed), is generated by hand (`pnpm generate:code-syntax`) and is
// checked by `pnpm check:tokens`.

import fs from "node:fs";
import { cssVariableName } from "../packages/tokens/lib/css-variable.js";

export const CODE_SYNTAX_FILE = "packages/tokens/io/code-syntax/web.json";
export const CSS_FILES = [
  "packages/tokens/dist/tokens.css",
  "packages/tokens/dist/semantic-light.css",
];

const DESCRIPTION =
  "Figma code syntax (WEB) Token Bridge sets on the variables. Generated by " +
  "scripts/generate-code-syntax.mjs from the sync tokens and the CSS naming in " +
  "packages/tokens/lib/css-variable.js; do not edit by hand and do not push. Keys are token " +
  "paths, values are the CSS usage.";

/** token path -> `var(--name)`, sorted by path. `tokens` is the Map from readSyncTokens. */
export function deriveCodeSyntax(tokens) {
  const syntax = {};
  for (const name of [...tokens.keys()].sort()) {
    const token = tokens.get(name);
    syntax[name] = `var(${cssVariableName(token, name.replace(/\./g, "-"))})`;
  }
  return syntax;
}

export function serializeCodeSyntax(syntax) {
  return (
    JSON.stringify({ description: DESCRIPTION, platform: "WEB", syntax }, null, 2) + "\n"
  );
}

/** Custom properties declared in the built CSS. */
export function declaredCssVariables(root = ".") {
  const declared = new Set();
  for (const file of CSS_FILES) {
    const css = fs.readFileSync(`${root}/${file}`, "utf8");
    for (const m of css.matchAll(/^\s*(--[\w-]+)\s*:/gm)) declared.add(m[1]);
  }
  return declared;
}

/** Problems with a code syntax map: a token that does not exist, a name the CSS does not declare, a duplicate. */
export function checkCodeSyntax(syntax, tokens, declared) {
  const problems = [];
  const used = new Map();
  for (const [path, value] of Object.entries(syntax)) {
    if (!tokens.has(path)) problems.push(`${path} is not a token`);
    const name = /^var\((--[\w-]+)\)$/.exec(value)?.[1];
    if (!name) {
      problems.push(`${path}: "${value}" is not var(--name)`);
      continue;
    }
    if (!declared.has(name)) problems.push(`${path}: ${name} is not declared in the built CSS`);
    if (used.has(name)) problems.push(`${path} and ${used.get(name)} share ${name}`);
    used.set(name, path);
  }
  return problems;
}
