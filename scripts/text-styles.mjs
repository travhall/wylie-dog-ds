// Text style definitions derived from the component tokens (Plan 206).
//
// Figma variables cannot carry a percent, so line height and letter spacing live
// on Figma text styles (Plan 204). Token Bridge creates and updates those styles
// from a committed definitions file, packages/tokens/io/styles/text-styles.json,
// that this module derives from the component tokens. The file holds token
// PATHS, never values: Token Bridge resolves them from the tokens it pulls.
//
// Owner decisions (2026-10-25, plan 206):
//   1. Granularity: one style per component font-size token, generated, so the
//      styles mirror the code and need no authoring. No hand-authored scale.
//   2. The file lives in packages/tokens/io/styles/ (outside io/sync, which Push
//      writes: styles are derived and never pushed). The generator is run by
//      hand (`pnpm generate:text-styles`); the tokens build does not run it.
//      `pnpm check:tokens` fails when the file is stale or names a missing token.
//
// A text part is a component token prefix with a font-size token:
//   <prefix>[.-]font-size[[.-](sm|md|lg|xl)]
// Its weight, line height and letter spacing (or tracking) tokens are the ones
// with the same prefix (a size-specific token wins over an unsized one). Only
// the font size is required: a part without a weight gets Regular, without a
// line height AUTO, without a tracking 0%. The font family is the primitive sans
// family unless the part has a font-family token of its own (badge.font-family, Plan 217).
//
// Style names are <prefix as a path>[/<size>] ("button/sm", "alert/title"), so
// the names a later builder run uses can match them where the structure agrees.
// Weight, line-height and tracking tokens that match no font-size token are
// reported (`orphans`), never paired by guesswork. A pair the owner has confirmed from
// the code is listed in PAIRS and fills in only what its style is missing (Plan 217).

import path from "node:path";
import { readSyncCollections } from "../packages/tokens/lib/read-sync.js";

export const SYNC_DIR = "packages/tokens/io/sync";
export const DEFINITIONS_FILE = "packages/tokens/io/styles/text-styles.json";
export const FONT_FAMILY_TOKEN = "typography.font-family.sans";

const SIZES = "sm|md|lg|xl";
const FONT_SIZE = new RegExp(`^(.*?)[.-]font-size(?:[.-](${SIZES}))?$`);
const PARTNER =
  /[.-](font-family|font-weight|line-height|letter-spacing|tracking)$/;

const DESCRIPTION =
  "Figma text styles Token Bridge creates and keeps in line with the tokens. " +
  "Generated by scripts/generate-text-styles.mjs from the component tokens; " +
  "do not edit by hand and do not push. Values are token paths, resolved when " +
  "Token Bridge pulls.";

/** Every token of every collection in the sync folder: name to token. */
export function readSyncTokens(root = ".") {
  const tokens = new Map();
  const collections = readSyncCollections(path.join(root, SYNC_DIR));
  for (const name of ["primitive", "semantic", "components"]) {
    // The collection a token came from, tagged as the file name it has always had.
    const file = `${name}.json`;
    for (const collection of collections[name]) {
      for (const content of Object.values(collection)) {
        for (const [name, token] of Object.entries(content.variables)) {
          tokens.set(name, { ...token, file });
        }
      }
    }
  }
  return tokens;
}

// Confirmed pairings: the weight, line height and tracking a part uses in the UI when
// their names do not share the font-size token's prefix. Each entry names the style by its
// font-size token and may add only kinds the style does not have. Nothing else uses these
// tokens' font size, so no other style is affected (owner, 2026-11-04). The other orphans
// share a font size with a part of a different weight (menubar trigger, label and item;
// calendar nav and header; ...), and a style holds one weight: those layers keep their
// weight as a node-level binding and are reported as orphans on purpose.
export const PAIRS = [
  {
    fontSize: "card.header.title.font-size",
    fontWeight: "card.title.font-weight",
    lineHeight: "card.title.line-height",
    letterSpacing: "card.title.letter-spacing",
  },
];

/** Derive the definitions from the tokens. Pure. Throws on a stale pair. */
export function deriveTextStyles(tokens, pairs = []) {
  const names = [...tokens.keys()].filter(
    (name) => tokens.get(name).file === "components.json"
  );
  const exists = new Set(names);
  const used = new Set();
  const styles = [];

  for (const name of names) {
    const match = FONT_SIZE.exec(name);
    if (!match) continue;
    const [, prefix, size] = match;

    const find = (...suffixes) => {
      for (const suffix of suffixes) {
        const candidates = size
          ? [
              `${prefix}.${suffix}.${size}`,
              `${prefix}-${suffix}-${size}`,
              `${prefix}.${suffix}-${size}`,
            ]
          : [];
        candidates.push(`${prefix}.${suffix}`, `${prefix}-${suffix}`);
        const hit = candidates.find((c) => exists.has(c));
        if (hit) return hit;
      }
      return undefined;
    };

    const family = find("font-family");
    const style = {
      name: prefix.replaceAll(".", "/") + (size ? `/${size}` : ""),
      fontFamily: family ?? FONT_FAMILY_TOKEN,
      fontSize: name,
    };
    const weight = find("font-weight");
    const lineHeight = find("line-height");
    const letterSpacing = find("letter-spacing", "tracking");
    if (weight) style.fontWeight = weight;
    if (lineHeight) style.lineHeight = lineHeight;
    if (letterSpacing) style.letterSpacing = letterSpacing;
    for (const token of [name, family, weight, lineHeight, letterSpacing]) {
      if (token) used.add(token);
    }
    styles.push(style);
  }

  for (const { fontSize, ...parts } of pairs) {
    const style = styles.find((s) => s.fontSize === fontSize);
    if (!style) throw new Error(`pair: no style has the font size ${fontSize}`);
    for (const [kind, token] of Object.entries(parts)) {
      if (!exists.has(token)) throw new Error(`pair: ${token} does not exist`);
      if (style[kind]) {
        throw new Error(
          `pair: ${style.name} already has a ${kind} (${style[kind]})`
        );
      }
      style[kind] = token;
      used.add(token);
    }
  }

  styles.sort((a, b) => a.name.localeCompare(b.name));
  const orphans = names.filter((name) => PARTNER.test(name) && !used.has(name));
  return { styles, orphans };
}

/** The file's content for some derived styles. */
export function serializeDefinitions(styles) {
  return JSON.stringify({ description: DESCRIPTION, styles }, null, 2) + "\n";
}

const MAX_ALIAS_DEPTH = 10;

/** A token's value after following `{alias}` chains; undefined when broken. */
export function resolveValue(tokens, name, depth = 0) {
  if (depth > MAX_ALIAS_DEPTH) return undefined;
  const token = tokens.get(name);
  if (!token) return undefined;
  const raw = token.$value;
  if (typeof raw === "string") {
    const alias = /^\{([^{}]+)\}$/.exec(raw.trim());
    if (alias) return resolveValue(tokens, alias[1], depth + 1);
  }
  return raw;
}

const isNumber = (v) => typeof v === "number";
const isEm = (v) => isNumber(v) || /^-?\d*\.?\d+(em)?$/.test(String(v).trim());

const KINDS = {
  fontFamily: (v) => typeof v === "string" && v.trim() !== "",
  fontSize: isNumber,
  fontWeight: isNumber,
  lineHeight: isNumber,
  letterSpacing: isEm,
};

/** Problems with a definitions list: unknown or unusable tokens, duplicates. */
export function checkReferences(styles, tokens) {
  const problems = [];
  const seen = new Set();
  for (const style of styles) {
    if (seen.has(style.name))
      problems.push(`${style.name}: duplicate style name`);
    seen.add(style.name);
    for (const [key, accepts] of Object.entries(KINDS)) {
      const token = style[key];
      if (token === undefined) {
        if (key === "fontFamily" || key === "fontSize") {
          problems.push(`${style.name}: ${key} is required`);
        }
        continue;
      }
      if (!tokens.has(token)) {
        problems.push(`${style.name}: ${key} token "${token}" does not exist`);
      } else if (!accepts(resolveValue(tokens, token))) {
        problems.push(
          `${style.name}: ${key} token "${token}" does not resolve to a usable value`
        );
      }
    }
  }
  return problems;
}
